#!/bin/bash
# Writes the frozen CentOS vault + EPEL archive repo files for EL6/EL7 images
# with a multi-line baseurl= list and failovermethod=priority.
#
# Why: on 2026-10-29 five el7 jobs on the Singapore runners died mid-download
# from vault.epel.cloud -- Cloudflare Free routed them to a European colo and
# truncated cache-hit bodies. Every repo had ONE baseurl, so yum's "Trying
# other mirror" had nowhere to go. Cloudflare stays first (fast, cached); the
# rest are independent non-CF mirrors of the same frozen trees.
#
# Usage: vault-repos.sh [base|scl|epel|all]   (default: all)
# Test overrides: VAULT_REPO_DIR, VAULT_RHEL, VAULT_ARCH, VAULT_AMZN.
set -eu

WHAT=${1:-all}
REPO_DIR=${VAULT_REPO_DIR:-/etc/yum.repos.d}
RHEL=${VAULT_RHEL:-$(rpm -E '0%{?rhel}')}
RHEL=$((10#${RHEL}))
AMZN=${VAULT_AMZN:-$(rpm -E '0%{?amzn}')}
AMZN=$((10#${AMZN}))
ARCH=${VAULT_ARCH:-$(uname -m)}

# Amazon Linux 2 also reports %rhel 7 but has its own repos.
if ((AMZN > 0)) || ((RHEL != 6 && RHEL != 7)); then
    exit 0
fi

# Same frozen tree on every mirror, laid out like vault.centos.org.
# vault.getpagespeed.com serves a local copy when present, else 302s to
# vault.centos.org: the slot for a mirror of our own, already in every client.
CENTOS_MIRRORS="https://vault.epel.cloud
https://vault.getpagespeed.com
https://ftp.iij.ad.jp/pub/linux/centos-vault
https://archive.kernel.org/centos-vault
https://mirror.nsc.liu.se/centos-store
https://linuxsoft.cern.ch/centos-vault
https://vault.centos.org"

# Laid out like archives.fedoraproject.org/pub/archive/epel.
EPEL_MIRRORS="https://archive.epel.cloud/pub/archive/epel
https://vault.getpagespeed.com/pub/archive/epel
https://ftp.iij.ad.jp/pub/linux/Fedora/archive/epel
https://archives.fedoraproject.org/pub/archive/epel
https://mirror.math.princeton.edu/pub/fedora-archive/epel
https://ftp-stud.hs-esslingen.de/pub/Mirrors/archive.fedoraproject.org/epel"

if ((RHEL == 7)); then
    VAULT_VER=7.9.2009
    # Non-x86_64 EL7 lives under altarch/ on every mirror.
    if [ "$ARCH" != x86_64 ]; then
        VAULT_VER=altarch/7.9.2009
    fi
    CENTOS_KEY=RPM-GPG-KEY-CentOS-7
    if [ "$ARCH" = aarch64 ]; then
        CENTOS_KEY=RPM-GPG-KEY-CentOS-7-aarch64
    fi
else
    VAULT_VER=6.10
    CENTOS_KEY=RPM-GPG-KEY-CentOS-6
fi

# baseurl= block: first mirror on the key line, the rest as continuations.
baseurls() {
    local mirrors="$1" path="$2" first=1 m
    while IFS= read -r m; do
        if ((first)); then
            echo "baseurl=${m}/${path}"
            first=0
        else
            echo "        ${m}/${path}"
        fi
    done <<< "$mirrors"
    echo "failovermethod=priority"
}

# section ID NAME PATH ENABLED KEY
centos_section() {
    echo "[$1]"
    echo "name=$2"
    baseurls "$CENTOS_MIRRORS" "${VAULT_VER}/$3"
    echo "gpgcheck=1"
    echo "enabled=$4"
    echo "gpgkey=file:///etc/pki/rpm-gpg/$5"
    echo "metadata_expire=never"
    echo
}

write_base() {
    {
        echo "# Generated by rpmbuilder vault-repos.sh: frozen CentOS ${VAULT_VER} vault"
        echo
        centos_section base 'CentOS-$releasever - Base' 'os/$basearch/' 1 "$CENTOS_KEY"
        centos_section updates 'CentOS-$releasever - Updates' 'updates/$basearch/' 1 "$CENTOS_KEY"
        centos_section extras 'CentOS-$releasever - Extras' 'extras/$basearch/' 1 "$CENTOS_KEY"
        centos_section centosplus 'CentOS-$releasever - Plus' 'centosplus/$basearch/' 0 "$CENTOS_KEY"
    } > "${REPO_DIR}/CentOS-Base.repo"
}

write_scl() {
    {
        echo "# Generated by rpmbuilder vault-repos.sh"
        echo
        centos_section centos-sclo-sclo 'CentOS-$releasever - SCLo sclo' 'sclo/$basearch/sclo/' 1 RPM-GPG-KEY-CentOS-SIG-SCLo
    } > "${REPO_DIR}/CentOS-SCLo-scl.repo"
    {
        echo "# Generated by rpmbuilder vault-repos.sh"
        echo
        centos_section centos-sclo-rh 'CentOS-$releasever - SCLo rh' 'sclo/$basearch/rh/' 1 RPM-GPG-KEY-CentOS-SIG-SCLo
    } > "${REPO_DIR}/CentOS-SCLo-scl-rh.repo"
}

write_epel() {
    {
        echo "# Generated by rpmbuilder vault-repos.sh: archived EPEL ${RHEL}"
        echo
        echo "[epel]"
        echo "name=Extra Packages for Enterprise Linux ${RHEL} - \$basearch"
        baseurls "$EPEL_MIRRORS" "${RHEL}/\$basearch"
        echo "enabled=1"
        echo "gpgcheck=1"
        echo "gpgkey=file:///etc/pki/rpm-gpg/RPM-GPG-KEY-EPEL-${RHEL}"
        echo "metadata_expire=never"
    } > "${REPO_DIR}/epel.repo"
}

case "$WHAT" in
    base) write_base ;;
    scl) write_scl ;;
    epel) write_epel ;;
    all) write_base; write_scl; write_epel ;;
    *) echo "usage: $0 [base|scl|epel|all]" >&2; exit 2 ;;
esac
